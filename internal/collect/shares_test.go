func TestParseExports(t *testing.T) {
	t.Parallel()
	content := `# /etc/exports generated by TrueNAS
/mnt/media/share 192.0.2.24/24(rw,sync,no_subtree_check,no_root_squash) 10.0.0.0/8(ro)
/mnt/tank/backup 192.0.2.10(rw,sync)
"/mnt/media/my share" *(ro,all_squash)
/mnt/plain
`
	got := parseExports(content, "/etc/exports")
	if len(got) != 4 {
		t.Fatalf("got %d exports, want 4: %+v", len(got), got)
	}

	if got[0].Path != "/mnt/media/share" || len(got[0].Clients) != 2 {
		t.Fatalf("first export parsed wrong: %+v", got[0])
	}
	c := got[0].Clients[0]
	if c.Spec != "192.0.2.24/24" || c.ReadOnly {
		t.Errorf("rw client parsed wrong: %+v", c)
	}
	if !got[0].Clients[1].ReadOnly {
		t.Errorf("ro client not marked read-only: %+v", got[0].Clients[1])
	}
	// no_root_squash is the option worth being able to find later.
	if !contains(c.Options, "no_root_squash") {
		t.Errorf("options lost: %v", c.Options)
	}

	// A quoted path with a space must not be split into path plus client.
	if got[2].Path != "/mnt/media/my share" {
		t.Errorf("quoted path = %q", got[2].Path)
	}
	if got[2].Clients[0].Spec != "*" {
		t.Errorf("wildcard client = %q", got[2].Clients[0].Spec)
	}

	// An export with no client list at all is valid; NFS defaults to
	// read-only, and recording that saves consumers from knowing it.
	if got[3].Path != "/mnt/plain" || len(got[3].Clients) != 0 {
		t.Errorf("bare export parsed wrong: %+v", got[3])
	}
}

// TestParseExportsContinuationLines uses the exact shape TrueNAS generates.
// The first version parsed this line-by-line and produced an export whose
// path was an IP address, plus a bogus "\" client on the real one.
func TestParseExportsContinuationLines(t *testing.T) {
	t.Parallel()
	content := "/mnt/media/share\\\n" +
		"\t192.0.2.10(sec=sys,rw,anonuid=0,anongid=0,all_squash,no_subtree_check)\\\n" +
		"\t192.0.2.24(sec=sys,rw,anonuid=0,no_subtree_check)\n" +
		"/mnt/tank/backup\\\n" +
		"\t192.0.2.11(sec=sys,rw,anonuid=0,anongid=0,all_squash,no_subtree_check)\n"

	got := parseExports(content, "/etc/exports")
	if len(got) != 2 {
		t.Fatalf("got %d exports, want 2: %+v", len(got), got)
	}
	if got[0].Path != "/mnt/media/share" {
		t.Errorf("path = %q, want /mnt/media/share", got[0].Path)
	}
	if len(got[0].Clients) != 2 {
		t.Fatalf("got %d clients, want 2: %+v", len(got[0].Clients), got[0].Clients)
	}
	for i, want := range []string{"192.0.2.10", "192.0.2.24"} {
		if got[0].Clients[i].Spec != want {
			t.Errorf("client %d spec = %q, want %q", i, got[0].Clients[i].Spec, want)
		}
		if got[0].Clients[i].ReadOnly {
			t.Errorf("client %d should be rw", i)
		}
	}
	if got[1].Path != "/mnt/tank/backup" || len(got[1].Clients) != 1 {
		t.Errorf("second export parsed wrong: %+v", got[1])
	}
	// No export may have an address as its path — the symptom of the bug.
	for _, e := range got {
		if !strings.HasPrefix(e.Path, "/") {
			t.Errorf("export path %q is not a path; continuation was mis-parsed", e.Path)
		}
	}
}

func TestParseNFSClientDefaultsToReadOnly(t *testing.T) {
	t.Parallel()
	if c := parseNFSClient("192.0.2.26"); !c.ReadOnly {
		t.Errorf("a client with no options must default to read-only: %+v", c)
	}
	if c := parseNFSClient("192.0.2.26(sync,no_subtree_check)"); !c.ReadOnly {
		t.Errorf("options without rw must stay read-only: %+v", c)
	}
	if c := parseNFSClient("192.0.2.26(rw)"); c.ReadOnly {
		t.Errorf("rw not honoured: %+v", c)
	}
}

func TestParseSMBConf(t *testing.T) {
	t.Parallel()
	content := `[global]
	workgroup = WORKGROUP
	server string = TrueNAS
	passdb backend = tdbsam

# a comment
; another comment

[media]
	path = /mnt/media/share
	comment = Media library
	read only = no
	guest ok = yes
	valid users = example-user

[backup]
	path = /mnt/tank/backup
	read only = yes

[printers]
	path = /var/spool/samba
`
	got := parseSMBConf(content, "/etc/smb4.conf")
	if len(got) != 2 {
		t.Fatalf("got %d shares, want 2 (global and printers excluded): %+v", len(got), got)
	}

	media := got[0]
	if media.Name != "media" || media.Path != "/mnt/media/share" || media.Comment != "Media library" {
		t.Errorf("media share parsed wrong: %+v", media)
	}
	// Keys contain spaces in smb.conf; they must survive as written.
	if media.Options["read only"] != "no" || media.Options["guest ok"] != "yes" {
		t.Errorf("spaced keys lost: %+v", media.Options)
	}
	if got[1].Name != "backup" || got[1].Options["read only"] != "yes" {
		t.Errorf("backup share parsed wrong: %+v", got[1])
	}
}

func TestParseSMBConfRedactsCredentials(t *testing.T) {
	t.Parallel()
	content := `[secure]
	path = /mnt/tank
	ldap admin dn = cn=admin,dc=lan
	ldap password = hunter2
	smb encrypt = required
`
	got := parseSMBConf(content, "/etc/samba/smb.conf")
	if len(got) != 1 {
		t.Fatalf("got %d shares", len(got))
	}
	opts := got[0].Options
	if strings.Contains(opts["ldap password"], "hunter2") {
		t.Errorf("password leaked: %q", opts["ldap password"])
	}
	if opts["smb encrypt"] != "required" {
		t.Errorf("non-secret altered: %q", opts["smb encrypt"])
	}
	if opts["path"] != "/mnt/tank" {
		t.Errorf("path altered: %q", opts["path"])
	}
}

func TestCutExportPath(t *testing.T) {
	t.Parallel()
	cases := []struct{ in, path, rest string }{
		{"/mnt/share *(ro)", "/mnt/share", "*(ro)"},
		{"/mnt/share\t192.0.2.0/24(rw)", "/mnt/share", "192.0.2.0/24(rw)"},
		{`"/mnt/my share" *(ro)`, "/mnt/my share", "*(ro)"},
		{"/mnt/bare", "/mnt/bare", ""},
	}
	for _, c := range cases {
		path, rest := cutExportPath(c.in)
		if path != c.path || rest != c.rest {
			t.Errorf("cutExportPath(%q) = (%q, %q), want (%q, %q)", c.in, path, rest, c.path, c.rest)
		}
	}
}

func contains(ss []string, s string) bool {
	for _, x := range ss {
		if x == s {
			return true
		}
	}
	return false
}
