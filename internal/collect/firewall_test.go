// Synthetic rulesets exercise hooks, policies, jumps, counters and empty tables.

// exampleNFT: base chains with hooks and policies, regular chains that are only
// reached by a jump, counters, quoted interface names, negated matches, and a
// FORWARD chain whose policy is drop while INPUT accepts.
const exampleNFT = `table ip filter {
	chain ts-input {
		iifname "lo" ip saddr 192.0.2.21 counter packets 2 bytes 64 accept
		iifname "tailscale0" counter packets 2 bytes 64 accept
		meta l4proto udp udp dport 41641 counter packets 2 bytes 64 accept
		iifname != "tailscale0" ip saddr 192.0.2.22/23 counter packets 2 bytes 64 return
		iifname != "tailscale0" ip saddr 192.0.2.20/10 counter packets 2 bytes 64 drop
	}
	chain INPUT {
		type filter hook input priority filter; policy accept;
		counter packets 2 bytes 64 jump ts-input
	}
	chain FORWARD {
		type filter hook forward priority filter; policy drop;
		counter packets 2 bytes 64 jump DOCKER-USER
		counter packets 2 bytes 64 jump DOCKER-ISOLATION-STAGE-1
	}
	chain DOCKER {
		iifname != "br-aaaa" oifname "br-aaaa" meta l4proto tcp ip daddr 192.0.2.30 tcp dport 8989 counter accept
	}
	chain DOCKER-USER {
		counter packets 2 bytes 64 return
	}
}
table ip nat {
	chain POSTROUTING {
		type nat hook postrouting priority srcnat; policy accept;
		oifname != "br-aaaa" ip saddr 192.0.2.0/24 counter masquerade
	}
	chain PREROUTING {
		type nat hook prerouting priority dstnat; policy accept;
		fib daddr type local counter jump DOCKER
	}
}
table ip6 filter {
	chain INPUT {
		type filter hook input priority filter; policy accept;
		counter packets 2 bytes 64 jump ts-input
	}
}
`

// emptyNFT: tables that exist and are completely empty. This is the case
// most likely to be misread, because "the ruleset parsed fine" and "there are
// no rules" look identical unless the verdict says so out loud.
const emptyNFT = `table ip filter {
}
table ip nat {
}
table ip6 filter {
}
table ip6 nat {
}
`

// emptyIPTables: iptables-save with every chain at its default and not one rule.
const emptyIPTables = `# Generated by iptables-save v1.8.9 on Mon Jan  1 00:00:00 2024
*mangle
:PREROUTING ACCEPT [0:0]
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
COMMIT
# Completed on Mon Jan  1 00:00:00 2024
# Generated by iptables-save v1.8.9 on Mon Jan  1 00:00:00 2024
*filter
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
COMMIT
# Completed on Mon Jan  1 00:00:00 2024
`

// lockedDownIPTables is a default-deny ruleset.
const lockedDownIPTables = `*filter
:INPUT DROP [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
:MYCHAIN - [0:0]
-A INPUT -i lo -j ACCEPT
-A INPUT -m state --state RELATED,ESTABLISHED -j ACCEPT
-A INPUT -p tcp -m tcp --dport 22 -j ACCEPT
-A MYCHAIN -j RETURN
COMMIT
`

func chainByName(t *testing.T, tables []inventory.FirewallTable, table, chain string) inventory.FirewallChain {
	t.Helper()
	for _, tb := range tables {
		if tb.Name != table {
			continue
		}
		for _, ch := range tb.Chains {
			if ch.Name == chain {
				return ch
			}
		}
	}
	t.Fatalf("no chain %s/%s in %+v", table, chain, tables)
	return inventory.FirewallChain{}
}

func TestParseNFT(t *testing.T) {
	t.Parallel()
	tables := parseNFT(exampleNFT)
	if len(tables) != 3 {
		t.Fatalf("got %d tables, want 3", len(tables))
	}
	if tables[0].Family != "ip" || tables[0].Name != "filter" {
		t.Errorf("first table = %s %s, want ip filter", tables[0].Family, tables[0].Name)
	}
	if tables[2].Family != "ip6" {
		t.Errorf("third table family = %q, want ip6", tables[2].Family)
	}

	input := chainByName(t, tables, "filter", "INPUT")
	if input.Hook != "input" || input.Policy != "accept" || input.Priority != "filter" {
		t.Errorf("INPUT = hook %q policy %q priority %q", input.Hook, input.Policy, input.Priority)
	}
	if len(input.Rules) != 1 || !strings.Contains(input.Rules[0], "jump ts-input") {
		t.Errorf("INPUT rules = %v", input.Rules)
	}

	fwd := chainByName(t, tables, "filter", "FORWARD")
	if fwd.Policy != "drop" {
		t.Errorf("FORWARD policy = %q, want drop", fwd.Policy)
	}

	// A regular chain has no hook and no policy, which is the distinction that
	// makes the verdict meaningful: a chain full of drops that nothing jumps
	// to filters nothing.
	ts := chainByName(t, tables, "filter", "ts-input")
	if ts.Hook != "" || ts.Policy != "" {
		t.Errorf("ts-input should be a regular chain, got hook %q policy %q", ts.Hook, ts.Policy)
	}
	if len(ts.Rules) != 5 {
		t.Errorf("ts-input rules = %d, want 5", len(ts.Rules))
	}
	// Rule bodies are kept verbatim, including the negated match.
	if !strings.Contains(ts.Rules[4], `iifname != "tailscale0"`) {
		t.Errorf("rule text was mangled: %q", ts.Rules[4])
	}
}

// Tables that exist and are empty must parse as exactly that, and must not
// collapse into "no tables" — which would be indistinguishable from a failed
// read.
func TestParseNFTEmptyTables(t *testing.T) {
	t.Parallel()
	tables := parseNFT(emptyNFT)
	if len(tables) != 4 {
		t.Fatalf("got %d tables, want 4", len(tables))
	}
	for _, tb := range tables {
		if len(tb.Chains) != 0 {
			t.Errorf("table %s %s has %d chains, want 0", tb.Family, tb.Name, len(tb.Chains))
		}
	}
}

func TestParseIPTablesSave(t *testing.T) {
	t.Parallel()
	tables := parseIPTablesSave(emptyIPTables, "ip")
	if len(tables) != 2 {
		t.Fatalf("got %d tables, want 2 (mangle, filter)", len(tables))
	}
	input := chainByName(t, tables, "filter", "INPUT")
	if input.Policy != "accept" {
		t.Errorf("INPUT policy = %q, want accept", input.Policy)
	}
	// The built-in chain name is mapped to the hook it corresponds to, which
	// is what lets one verdict function read both formats.
	if input.Hook != "input" {
		t.Errorf("INPUT hook = %q, want input", input.Hook)
	}
	if len(input.Rules) != 0 {
		t.Errorf("INPUT rules = %v, want none", input.Rules)
	}

	locked := parseIPTablesSave(lockedDownIPTables, "ip")
	li := chainByName(t, locked, "filter", "INPUT")
	if li.Policy != "drop" || len(li.Rules) != 3 {
		t.Errorf("locked INPUT = policy %q rules %d, want drop/3", li.Policy, len(li.Rules))
	}
	// A user chain has "-" for a policy and is not a base chain.
	mine := chainByName(t, locked, "filter", "MYCHAIN")
	if mine.Policy != "" || mine.Hook != "" {
		t.Errorf("MYCHAIN should not look like a base chain: policy %q hook %q", mine.Policy, mine.Hook)
	}
	if len(mine.Rules) != 1 {
		t.Errorf("MYCHAIN rules = %d, want 1", len(mine.Rules))
	}
}

// "Status: disabled/running" is a genuinely misleading string to skim: the
// second word is the service, which runs happily while the firewall is off.
func TestParsePVEFirewallStatus(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		out     string
		enabled bool
		status  string
	}{
		{"Status: disabled/running\n", false, "disabled/running"},
		{"Status: enabled/running\n", true, "enabled/running"},
		{"Status: disabled/stopped\n", false, "disabled/stopped"},
		// Perl locale warnings go to stderr, but be robust to them anyway.
		{"perl: warning: Setting locale failed.\nStatus: enabled/running\n", true, "enabled/running"},
		{"", false, ""},
	} {
		got := parsePVEFirewallStatus(tc.out)
		if got.Enabled != tc.enabled || got.Status != tc.status {
			t.Errorf("parsePVEFirewallStatus(%q) = %+v, want enabled=%v status=%q",
				tc.out, got, tc.enabled, tc.status)
		}
	}
}

// The verdict is the whole point of the section, and the case that matters
// most is the one an earlier version of this code got wrong: host-a's INPUT
// chain has a rule — a jump into Tailscale's chain — while its policy is
// accept. Counting that as "filtered" reported a host with forty LAN-reachable
// ports as protected.
func TestInboundPostureDoesNotMistakeRulesForFiltering(t *testing.T) {
	t.Parallel()
	fw := &inventory.Firewall{Available: true, Tables: parseNFT(exampleNFT)}
	posture, filters, why := assessInbound(fw)

	if posture != inventory.PostureDefaultAllow {
		t.Errorf("posture = %q, want default-allow: the policy is accept and only the "+
			"default verdict settles reachability", posture)
	}
	if filters {
		t.Error("a jump to Tailscale's chain was counted as inbound filtering")
	}
	if !strings.Contains(why, "accept") {
		t.Errorf("summary should say the default is accept: %q", why)
	}
}

func TestInboundPostureCases(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name    string
		fw      *inventory.Firewall
		posture inventory.Posture
		filters bool
	}{
		{
			name:    "empty nftables tables",
			fw:      &inventory.Firewall{Available: true, Tables: parseNFT(emptyNFT)},
			posture: inventory.PostureDefaultAllow,
		},
		{
			name:    "bare iptables, everything accept",
			fw:      &inventory.Firewall{Available: true, Tables: parseIPTablesSave(emptyIPTables, "ip")},
			posture: inventory.PostureDefaultAllow,
		},
		{
			name:    "a real default-deny",
			fw:      &inventory.Firewall{Available: true, Tables: parseIPTablesSave(lockedDownIPTables, "ip")},
			posture: inventory.PostureDefaultDeny,
			filters: true,
		},
		{
			// Unreadable is emphatically not "no rules". Conflating them is
			// the most dangerous misreading this section allows.
			name:    "could not read the filter",
			fw:      &inventory.Firewall{Available: false},
			posture: inventory.PostureUnknown,
		},
		{
			// Proxmox's own layer sits above nftables and has its own switch.
			name: "proxmox firewall enabled",
			fw: &inventory.Firewall{Available: true,
				Tables:  parseIPTablesSave(emptyIPTables, "ip"),
				Proxmox: &inventory.ProxmoxFirewall{Enabled: true, Status: "enabled/running"}},
			posture: inventory.PostureDefaultDeny,
			filters: true,
		},
		{
			name: "proxmox firewall disabled leaves the raw verdict alone",
			fw: &inventory.Firewall{Available: true,
				Tables:  parseIPTablesSave(emptyIPTables, "ip"),
				Proxmox: &inventory.ProxmoxFirewall{Enabled: false, Status: "disabled/running"}},
			posture: inventory.PostureDefaultAllow,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			posture, filters, why := assessInbound(tc.fw)
			if posture != tc.posture || filters != tc.filters {
				t.Errorf("got posture %q filters %v, want %q %v (%s)",
					posture, filters, tc.posture, tc.filters, why)
			}
			if why == "" {
				t.Error("the verdict has no explanation; the bare value invites " +
					"the reader to assume a bug rather than a finding")
			}
		})
	}
}
